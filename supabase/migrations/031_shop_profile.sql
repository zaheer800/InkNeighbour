-- ── 1. owners: banner image + short tagline ──────────────────
-- Same RLS pattern as other public shop fields (shop_address, locality, ...):
-- owners already have an UPDATE policy on their own row and there is already
-- a public SELECT policy on owners (ShopPage/Find query these anonymously
-- today), and RLS in Postgres is row-level, not column-level — so no new
-- policies are needed for these two columns.
ALTER TABLE owners ADD COLUMN IF NOT EXISTS banner_url text;
ALTER TABLE owners ADD COLUMN IF NOT EXISTS description text;

DO $$
BEGIN
  IF NOT EXISTS (
    SELECT 1 FROM pg_constraint WHERE conname = 'owners_description_length'
  ) THEN
    ALTER TABLE owners ADD CONSTRAINT owners_description_length
      CHECK (description IS NULL OR char_length(description) <= 200);
  END IF;
END $$;

-- ── 2. service_menu: allow owner-defined custom services ─────
-- Keep service_code (needed for the UNIQUE(owner_id, service_code) index and
-- as the stable key the UI toggles on/off). Add `name` for the human-entered
-- label of a custom service, and `is_preset` so the UI can still render the
-- 5 original codes as quick-add chips with their existing i18n labels.
ALTER TABLE service_menu ADD COLUMN IF NOT EXISTS name text;
ALTER TABLE service_menu ADD COLUMN IF NOT EXISTS is_preset boolean NOT NULL DEFAULT false;

-- Backfill: every row that already exists today uses one of the 5 preset
-- codes (seed_service_menu only ever inserted those) — mark them as presets.
UPDATE service_menu SET is_preset = true
  WHERE service_code IN ('scan', 'photocopy', 'binding', 'lamination', 'passport_photo')
    AND is_preset = false;

-- Loosen the old 5-value CHECK: presets must still be one of the 5 codes,
-- but a non-preset row can carry any short owner-chosen code (generated by
-- the client, e.g. `custom_<random>`), and must carry a display name.
ALTER TABLE service_menu DROP CONSTRAINT IF EXISTS service_menu_service_code_check;
ALTER TABLE service_menu ADD CONSTRAINT service_menu_service_code_check
  CHECK (
    (is_preset AND service_code IN ('scan', 'photocopy', 'binding', 'lamination', 'passport_photo'))
    OR (NOT is_preset AND char_length(service_code) <= 60)
  );

DO $$
BEGIN
  IF NOT EXISTS (
    SELECT 1 FROM pg_constraint WHERE conname = 'service_menu_name_length'
  ) THEN
    ALTER TABLE service_menu ADD CONSTRAINT service_menu_name_length
      CHECK (name IS NULL OR char_length(name) <= 60);
  END IF;
  IF NOT EXISTS (
    SELECT 1 FROM pg_constraint WHERE conname = 'service_menu_custom_requires_name'
  ) THEN
    ALTER TABLE service_menu ADD CONSTRAINT service_menu_custom_requires_name
      CHECK (is_preset OR name IS NOT NULL);
  END IF;
END $$;

-- seed_service_menu is called once at registration for new shop-type owners.
-- Re-create it so newly seeded rows are correctly flagged as presets (the
-- column default is false, which would otherwise mislabel every new signup).
CREATE OR REPLACE FUNCTION seed_service_menu(p_owner_id UUID)
RETURNS void
LANGUAGE plpgsql
SECURITY DEFINER
AS $$
BEGIN
  INSERT INTO service_menu (owner_id, service_code, is_enabled, is_preset)
  VALUES
    (p_owner_id, 'scan',           false, true),
    (p_owner_id, 'photocopy',      false, true),
    (p_owner_id, 'binding',        false, true),
    (p_owner_id, 'lamination',     false, true),
    (p_owner_id, 'passport_photo', false, true)
  ON CONFLICT (owner_id, service_code) DO NOTHING;
END;
$$;

