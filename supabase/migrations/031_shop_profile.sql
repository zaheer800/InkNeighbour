-- ── 3. logos bucket: formalize policies on the already-existing bucket ───
-- The `logos` bucket exists in the live project (created out-of-band) but
-- had zero storage.objects policies, so nothing could upload to it yet.
insert into storage.buckets (id, name, public, file_size_limit, allowed_mime_types)
values ('logos', 'logos', true, 5242880, array['image/png','image/jpeg','image/jpg','image/webp','image/gif'])
on conflict (id) do update
  set public = true,
      file_size_limit = 5242880,
      allowed_mime_types = array['image/png','image/jpeg','image/jpg','image/webp','image/gif'];

-- Path convention: logos/{owner_id}/banner.<ext> — owner can only touch the
-- folder matching their own owners.id.
DROP POLICY IF EXISTS "Owner upload own banner" ON storage.objects;
CREATE POLICY "Owner upload own banner"
  ON storage.objects FOR INSERT TO authenticated
  WITH CHECK (
    bucket_id = 'logos'
    AND (storage.foldername(name))[1] = (SELECT id::text FROM owners WHERE user_id = auth.uid())
  );

DROP POLICY IF EXISTS "Owner update own banner" ON storage.objects;
CREATE POLICY "Owner update own banner"
  ON storage.objects FOR UPDATE TO authenticated
  USING (
    bucket_id = 'logos'
    AND (storage.foldername(name))[1] = (SELECT id::text FROM owners WHERE user_id = auth.uid())
  )
  WITH CHECK (
    bucket_id = 'logos'
    AND (storage.foldername(name))[1] = (SELECT id::text FROM owners WHERE user_id = auth.uid())
  );

DROP POLICY IF EXISTS "Owner delete own banner" ON storage.objects;
CREATE POLICY "Owner delete own banner"
  ON storage.objects FOR DELETE TO authenticated
  USING (
    bucket_id = 'logos'
    AND (storage.foldername(name))[1] = (SELECT id::text FROM owners WHERE user_id = auth.uid())
  );

DROP POLICY IF EXISTS "Public read logos" ON storage.objects;
CREATE POLICY "Public read logos"
  ON storage.objects FOR SELECT
  USING (bucket_id = 'logos');
